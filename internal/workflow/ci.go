package workflow

// Verification in the owner's CI, for people with no container runtime on their own machine.
//
// The workflow's state lives in the local Git directory, so a fresh CI checkout has none: it
// cannot advance phases, and it must not, because CI is not the owner. What it can do is run
// exactly the checks `workflow verify` runs — the product's profile plus the security floor —
// in the same pinned, network-less container, and report them on the pull request. That gives
// an owner without Docker the same isolated evidence, visible where the change is reviewed,
// while the gates stay where they are.

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// VerifyProduct runs the product's declared checks without workflow state. With image empty it
// uses the verifier recorded by prepare-verifier for this profile.
func VerifyProduct(ctx context.Context, root, image string) (Verification, error) {
	s, err := New(root)
	if err != nil {
		return Verification{}, err
	}
	p, _, err := s.loadArtifacts()
	if err != nil {
		return Verification{}, err
	}
	commands, err := commandsFor(p)
	if err != nil {
		return Verification{}, err
	}
	if image == "" {
		r, err := s.LoadVerifier()
		if err != nil || r.Profile != p.Profile || r.Image == "" {
			return Verification{}, errors.New("no verifier image prepared for this profile; run agentarch workflow prepare-verifier first or pass --image")
		}
		image = r.Image
	}
	if !imageDigest.MatchString(image) && !localImageID.MatchString(image) {
		return Verification{}, errors.New("verifier image must be pinned by @sha256 digest or be a local sha256 image id")
	}
	runner := &ContainerRunner{Image: image}
	fingerprint, err := s.fingerprint(p.Profile)
	if err != nil {
		return Verification{}, err
	}
	v := Verification{Fingerprint: fingerprint, StartedAt: time.Now().UTC(), Isolation: runner.Isolation(), Checks: []CheckResult{}, Passed: true}
	for _, command := range commands {
		check := runner.Run(ctx, s.Root, command)
		v.Checks = append(v.Checks, check)
		if check.Status != "passed" {
			v.Passed = false
		}
		if ctx.Err() != nil {
			v.Passed = false
			break
		}
	}
	if after, err := s.fingerprint(p.Profile); err != nil || after != fingerprint {
		v.Passed = false
		v.Checks = append(v.Checks, CheckResult{ID: "source-stability", Subject: "product", Status: "inconclusive", ExitCode: -1, Message: "Source changed or became unavailable during verification."})
	}
	v.FinishedAt = time.Now().UTC()
	return v, nil
}

// CIWorkflowPath is where the GitHub Actions template is written.
const CIWorkflowPath = ".github/workflows/agentarch-verify.yml"

// CIWorkflow renders the GitHub Actions workflow. installRef is the agenteARQ release whose
// installer is used; base is required for the universal profile, whose toolchain is the
// project's choice.
func CIWorkflow(profile, installRef, base string) (string, error) {
	if profile == "universal" && base == "" {
		return "", errors.New("the universal profile needs --base: the image that provides the programs your checks run, pinned by @sha256 digest")
	}
	if base != "" && !pinnedImage.MatchString(base) {
		return "", errors.New("--base must be an image reference pinned by @sha256 digest")
	}
	prepare := "agentarch workflow prepare-verifier --engine docker"
	if base != "" {
		prepare += " --base " + base
	}
	return fmt.Sprintf(`# Generated by agentarch workflow ci-template. It runs the same isolated checks as
# agentarch workflow verify — the %s profile and the security floor, in a pinned container
# with no network — on every pull request, so an owner without Docker sees the evidence here.
# CI never advances the workflow: phases, reviews and releases stay with the owner.
name: agentarch verify

on:
  pull_request:
  push:
    branches: [main]

permissions:
  contents: read

jobs:
  verify:
    runs-on: ubuntu-latest
    timeout-minutes: 45
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
      - name: install agentarch (signature and checksum verified)
        run: |
          curl -fsSL https://raw.githubusercontent.com/Everton-baptista/agenteARQ/%s/scripts/install.sh \
            | AGENTARCH_BIN_DIR="$HOME/.local/bin" sh
          echo "$HOME/.local/bin" >> "$GITHUB_PATH"
      - name: build the pinned verifier image (the only step with network)
        run: %s
      - name: verify in the isolated container
        run: agentarch workflow ci-verify
`, profile, installRef, prepare), nil
}

// WriteCIWorkflow writes the template, refusing to replace an existing file.
func (s *Service) WriteCIWorkflow(installRef, base string) (string, error) {
	p, _, err := s.loadArtifacts()
	if err != nil {
		return "", err
	}
	body, err := CIWorkflow(p.Profile, installRef, base)
	if err != nil {
		return "", err
	}
	path := filepath.Join(s.Root, filepath.FromSlash(CIWorkflowPath))
	if _, err := os.Lstat(path); err == nil {
		return "", fmt.Errorf("refusing to overwrite %s", CIWorkflowPath)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	return CIWorkflowPath, atomicWrite(path, []byte(body), 0o644)
}

// CISummary is the Markdown a CI job shows for a verification.
func CISummary(v Verification) string {
	var b strings.Builder
	verdict := "passed"
	if !v.Passed {
		verdict = "did not pass"
	}
	fmt.Fprintf(&b, "### agentarch verification %s\n\n| Check | Status |\n|---|---|\n", verdict)
	for _, c := range v.Checks {
		fmt.Fprintf(&b, "| %s | %s |\n", c.ID, c.Status)
	}
	b.WriteString("\nThe checks ran in a pinned container with no network. This records evidence for the pull request; it does not advance the workflow.\n")
	return b.String()
}
